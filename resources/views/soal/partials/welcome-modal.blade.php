            if (modalEl) {
                const modal = new bootstrap.Modal(modalEl);
                modal.show();
            }
        }
    });

    function dismissSmartSoalModal() {
        const checkbox = document.getElementById('dontShowSmartSoalModalAgain');
        if (checkbox && checkbox.checked) {
            localStorage.setItem('smart_soal_welcome_dismissed', 'true');
        }
    }

    function showSmartSoalGuide() {
        const modalEl = document.getElementById('modalWelcomeSmartSoal');
        if (modalEl) {
